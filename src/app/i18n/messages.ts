export const catalogs: Record<SettingsLanguage, Record<MessageKey, string>> = {
  en: en as Record<MessageKey, string>,
  fr
};

export function translate(language: SettingsLanguage, key: MessageKey, params?: MessageParams): string {
  const template = catalogs[language][key] ?? catalogs.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? '' : String(value);
  });
}
