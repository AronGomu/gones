#!/usr/bin/env node
/**
 * Generates `DEMO_ACCOUNTS.md` from the demo development environment (ADR 0030).
 *
 * The roster lives in `fixtures/dev-environments/demo/`, the shared password in
 * `scripts/dev-accounts.mjs` (ADR 0029), so a hand-written account list can only drift away from
 * what the seeding actually produces. Run with `npm run docs:demo-accounts`; the output file is
 * committed and `ops/demo-accounts-doc.test.ts` fails when it no longer matches the fixtures.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEV_PASSWORD } from './dev-accounts.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ACCOUNTS_FILE = 'fixtures/dev-environments/demo/accounts.json';
const ORGANIZATIONS_FILE = 'fixtures/dev-environments/demo/organizations.json';
const OUTPUT_FILE = 'DEMO_ACCOUNTS.md';

const CAPABILITIES = {
  Admin: 'Everything: admin screens, all organizations, publish for any organization',
  Organizer: 'Create and publish events for the organizations listed',
  User: 'Browse the calendar, register for events, manage own registrations'
};

/**
 * The seeding writes `email_confirmed = false` only for an explicit `false`, and so does this.
 *
 * An unknown role throws rather than printing an empty cell: a fixture role this file cannot
 * describe is a documentation gap, and a silent blank column would pass the drift test.
 */
function capability(account) {
  const base = CAPABILITIES[account.role];
  if (!base) throw new Error(`No documented capability for the role "${account.role}" (${account.email}).`);
  return account.emailConfirmed === false ? `${base}, cannot write until the email is verified` : base;
}

/** Nobody owns an organization (ADR 0041), so the column lists the ones the account organizes. */
function memberOrganizations(account, organizations) {
  const joined = organizations
    .filter((organization) => (organization.memberEmails ?? []).includes(account.email))
    .map((organization) => organization.name);
  return joined.length ? joined.join(', ') : '—';
}

/** The full markdown file, as a string, so the drift test can compare it to the committed one. */
export function renderDemoAccountsDoc(accounts, organizations, password) {
  const rows = accounts.map((account) => [
    account.email,
    account.username,
    account.role,
    account.emailConfirmed === false ? 'no' : 'yes',
    memberOrganizations(account, organizations),
    capability(account)
  ]);

  return [
    '# Demo accounts',
    '',
    `<!-- Generated by \`scripts/generate-demo-accounts-doc.mjs\` from \`${ACCOUNTS_FILE}\` and \`${ORGANIZATIONS_FILE}\`. Do not edit by hand: run \`npm run docs:demo-accounts\`. -->`,
    '',
    `Generated file. Edit \`${ACCOUNTS_FILE}\` or \`${ORGANIZATIONS_FILE}\` and re-run \`npm run docs:demo-accounts\` — never this file.`,
    '',
    '## Loading them',
    '',
    '```bash',
    'npm run dev -- --env=demo   # resets the local database and seeds every account below',
    'npm run dev:accounts        # the two ADR 0029 accounts only, onto a stack already up',
    '```',
    '',
    `Every account shares the same password: \`${password}\`.`,
    '',
    '## The accounts',
    '',
    '| Email | Username | Role | Email verified | Organizations | What they can do |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row.join(' | ')} |`),
    ''
  ].join('\n');
}

function main() {
  const read = (file) => JSON.parse(readFileSync(join(ROOT, file), 'utf8'));
  const doc = renderDemoAccountsDoc(read(ACCOUNTS_FILE), read(ORGANIZATIONS_FILE), DEV_PASSWORD);

  writeFileSync(join(ROOT, OUTPUT_FILE), doc, 'utf8');
  console.log(`Wrote ${OUTPUT_FILE} from ${ACCOUNTS_FILE} and ${ORGANIZATIONS_FILE}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
